            report += f"   ➔ 💰 سود: {res['total_profit_million']:<8} م.تومان | 🌾 گندم: {res['wheat_ha']:<5} | 🌽 ذرت: {res['corn_ha']:<5} | 🌾 جو: {res['barley_ha']:<5}\n"
